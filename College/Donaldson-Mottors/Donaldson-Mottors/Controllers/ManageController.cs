        //
        // GET: /Manage/ChangeDetailsCustomer
        //Allows the Customer to change their own details
        [HttpGet]
        [Authorize]
        public ActionResult ChangeDetails()
        {
            var userId = User.Identity.GetUserId(); //Get user's Id
            var customer = db.Users.OfType<Customer>() //Get User using their Id
                      .SingleOrDefault(c => c.Id == userId);
            if (customer == null) return HttpNotFound(); //if user is not found throw error

            //use the model to get the current values to display
            var model = new ChangeDetailsViewModel
                {
                    Email = customer.Email,
                    Name = customer.Name,
                    Street = customer.Street,
                    Town = customer.Town,
                    Postcode = customer.Postcode,
                    TelephoneNo = customer.TelephoneNo

                };

            return View(model); //pass in the current profile details
        }

        // POST: /Manage/ChangeDetailsCustomer
        [HttpPost]
        [Authorize]
        public async Task<ActionResult> ChangeDetails(ChangeDetailsViewModel model) //pass in the updated profile
        {
            if (!ModelState.IsValid) return View(model); //check if modelstate is valid, return to page if not valid

            var userId = User.Identity.GetUserId(); //get Id
            var customer = db.Users.OfType<Customer>()
                      .SingleOrDefault(c => c.Id == userId);// get user
            if (customer == null) return HttpNotFound(); //if user is not found throw error

            //Update User Feilds
            customer.UserName = model.Email;
            customer.Email = model.Email;
            customer.Name = model.Name;
            customer.Street = model.Street;
            customer.Town = model.Town;
            customer.Postcode = model.Postcode;
            customer.TelephoneNo = model.TelephoneNo;

            //This code below is used to update the Customers's password
            if (!string.IsNullOrWhiteSpace(model.Password))
            {
                var result = await UserManager.RemovePasswordAsync(userId); //if new password is to be added

                if (result.Succeeded)
                {
                    await UserManager.AddPasswordAsync(userId, model.Password); //new password added
                }
            }

            db.SaveChanges(); //updatest the User in the DB

            TempData["ChangeDetailsAsCustomerSuccess"] = "Profile updated successfully!";//sends a message to index saying "success"
            return RedirectToAction("Index", "Home"); //Redirect user to the home page
        }


